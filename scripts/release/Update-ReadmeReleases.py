#!/usr/bin/env python3
"""Render the README's stable Desktop/Android release information from GitHub metadata."""

import argparse
from datetime import datetime
import json
from pathlib import Path
import re
from urllib.parse import quote

START = "<!-- BEGIN GENERATED RELEASES -->"
END = "<!-- END GENERATED RELEASES -->"
TAG = re.compile(r"^(android-)?v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")


def render(releases, repository):
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("Invalid GitHub repository name")
    # gh api --paginate --slurp emits one array per page.
    releases = [item for page in releases for item in page] if releases and isinstance(releases[0], list) else releases
    latest = {}
    for release in releases:
        match = TAG.fullmatch(release.get("tag_name", ""))
        if not match or release.get("draft") or release.get("prerelease") or not release.get("published_at"):
            continue
        channel = "Android" if match[1] else "Desktop / Linux"
        version = tuple(int(match[i]) for i in (2, 3, 4))
        if channel not in latest or version > latest[channel][0]:
            latest[channel] = (version, release)

    lines = [START, "## Latest releases", "",
             "<!-- Generated by scripts/release/Update-ReadmeReleases.py; edit the generator, not this block. -->", "",
             "| Platform | Latest stable release | Published (UTC) | Downloads and release information |",
             "| --- | --- | --- | --- |"]
    base = f"https://github.com/{repository}/releases"
    for channel in ("Desktop / Linux", "Android"):
        if channel not in latest:
            lines.append(f"| {channel} | No stable release published | — | [All releases]({base}) |")
            continue
        _, release = latest[channel]
        tag = release["tag_name"]
        url = f"{base}/tag/{tag}"
        published = datetime.fromisoformat(release["published_at"].replace("Z", "+00:00")).date().isoformat()
        downloads = []
        # Construct links from the trusted repository/tag and allowlisted asset names.
        for asset in sorted(release.get("assets", []), key=lambda item: item["name"]):
            name = asset["name"]
            if channel == "Android" and re.fullmatch(r"OTP-Harbor-android-universal-[0-9.]+\.apk", name):
                label = "APK"
            elif channel == "Desktop / Linux" and re.fullmatch(r"otp-harbor_[0-9.]+_amd64\.deb", name):
                label = "DEB"
            elif channel == "Desktop / Linux" and re.fullmatch(r"OTP-Harbor-linux-x64-[0-9.]+\.tar\.gz", name):
                label = "Linux tarball"
            elif name in ("SHA256SUMS", "release-artifacts-v2.json"):
                label = "Checksums" if name == "SHA256SUMS" else "Integrity metadata"
            else:
                continue
            downloads.append(f"[{label}]({base}/download/{tag}/{quote(name, safe='')})")
        downloads.append(f"[Release notes]({url})")
        lines.append(f"| {channel} | [{tag}]({url}) | {published} | {' · '.join(downloads)} |")
    lines += ["", "Desktop and Android versions ship independently. This table tracks published stable GitHub releases; Windows availability and updates are managed separately by the Microsoft Store.", END]
    return "\n".join(lines)


def update_readme(content, releases, repository):
    if content.count(START) != 1 or content.count(END) != 1 or content.index(END) < content.index(START):
        raise ValueError("README must contain exactly one ordered pair of generated release markers")
    start = content.index(START)
    end = content.index(END) + len(END)
    return content[:start] + render(releases, repository) + content[end:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--releases-json", type=Path, required=True)
    parser.add_argument("--readme", type=Path, default=Path("readme.md"))
    parser.add_argument("--repository", default="Legends/otp-harbor")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = args.readme.read_text(encoding="utf-8")
    updated = update_readme(content, json.loads(args.releases_json.read_text(encoding="utf-8-sig")), args.repository)
    if args.check:
        if updated != content:
            parser.exit(1, "README release information is stale.\n")
    elif updated != content:
        args.readme.write_text(updated, encoding="utf-8", newline="\n")
        print("Updated README release information.")


if __name__ == "__main__":
    main()
